import { mkdir, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const PROJECT_ROOT = process.cwd();
const MONTHS_DIR = path.join(PROJECT_ROOT, 'public', 'memories', 'months');
const OUTPUT_DIR = path.join(PROJECT_ROOT, 'src', 'data');
const OUTPUT_FILE = path.join(OUTPUT_DIR, 'memoriesManifest.js');

const MONTH_DIR_PATTERN = /^\d{4}-\d{2}$/;
const IMAGE_NAME_PATTERN = /^image-(\d+)\.(.+)$/i;
const VIDEO_NAME_PATTERN = /^vid-(\d+)\.(.+)$/i;

const IMAGE_EXTENSIONS = new Set(['jpg', 'jpeg', 'png', 'webp']);
const VIDEO_EXTENSIONS = new Set(['mp4', 'webm', 'mov', 'mp4.mp4', 'mov.mp4']);

function compareByIndex(a, b) {
  if (a.index !== b.index) return a.index - b.index;
  return a.file.localeCompare(b.file);
}

function normalizeExtension(ext) {
  return ext.toLowerCase();
}

async function generateManifest() {
  const monthDirEntries = await readdir(MONTHS_DIR, { withFileTypes: true });
  const monthDirs = monthDirEntries
    .filter((entry) => entry.isDirectory() && MONTH_DIR_PATTERN.test(entry.name))
    .map((entry) => entry.name)
    .sort();

  const manifest = {};

  for (const monthId of monthDirs) {
    const monthPath = path.join(MONTHS_DIR, monthId);
    const entries = await readdir(monthPath, { withFileTypes: true });
    const files = entries.filter((entry) => entry.isFile()).map((entry) => entry.name);

    const images = [];
    const videos = [];

    for (const file of files) {
      const imageMatch = file.match(IMAGE_NAME_PATTERN);
      if (imageMatch) {
        const ext = normalizeExtension(imageMatch[2]);
        if (IMAGE_EXTENSIONS.has(ext)) {
          images.push({ index: Number.parseInt(imageMatch[1], 10), file });
        }
        continue;
      }

      const videoMatch = file.match(VIDEO_NAME_PATTERN);
      if (videoMatch) {
        const ext = normalizeExtension(videoMatch[2]);
        if (VIDEO_EXTENSIONS.has(ext)) {
          videos.push({ index: Number.parseInt(videoMatch[1], 10), file });
        }
      }
    }

    images.sort(compareByIndex);
    videos.sort(compareByIndex);

    manifest[monthId] = {
      images: images.map((item) => item.file),
      videos: videos.map((item) => item.file),
    };
  }

  await mkdir(OUTPUT_DIR, { recursive: true });

  const output = `// Auto-generated by scripts/generate-memories-manifest.mjs\n// Do not edit manually.\nexport const MONTH_MEDIA_MANIFEST = ${JSON.stringify(manifest, null, 2)};\n`;
  await writeFile(OUTPUT_FILE, output, 'utf8');

  console.log(`Generated manifest: ${path.relative(PROJECT_ROOT, OUTPUT_FILE)}`);
  console.log(`Months indexed: ${monthDirs.length}`);
}

generateManifest().catch((error) => {
  console.error(error);
  process.exit(1);
});
